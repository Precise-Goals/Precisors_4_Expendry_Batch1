#!/usr/bin/env python3
"""
Sync root .env variables to packages/web/.env.local with NEXT_PUBLIC_ prefixes.
Ensures Next.js client-side bundles receive Firebase and MST constants.
"""

import os
from pathlib import Path

ROOT_DIR = Path(__file__).resolve().parent.parent
ENV_PATH = ROOT_DIR / ".env"
WEB_ENV_LOCAL_PATH = ROOT_DIR / "packages" / "web" / ".env.local"

CLIENT_EXPOSE_PREFIXES = (
    "FIREBASE_",
    "MST_",
    "CHAIN_ID",
    "SARVAM_",
)

def sync_env():
    if not ENV_PATH.exists():
        print(f"[WARN] No .env found at {ENV_PATH}")
        return

    lines = ENV_PATH.read_text(encoding="utf-8").splitlines()
    synced_lines = [
        "# Auto-generated by scripts/sync_env.py from root .env",
        "# DO NOT COMMIT TO VERSION CONTROL",
        "",
    ]

    for line in lines:
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            continue
        if "=" in stripped:
            key, val = stripped.split("=", 1)
            key = key.strip()
            val = val.strip()

            # Preserve original key
            synced_lines.append(f"{key}={val}")

            # If it belongs to client exposed variables, also add NEXT_PUBLIC_ prefix
            if any(key.startswith(prefix) for prefix in CLIENT_EXPOSE_PREFIXES):
                if not key.startswith("NEXT_PUBLIC_"):
                    synced_lines.append(f"NEXT_PUBLIC_{key}={val}")

    WEB_ENV_LOCAL_PATH.parent.mkdir(parents=True, exist_ok=True)
    WEB_ENV_LOCAL_PATH.write_text("\n".join(synced_lines) + "\n", encoding="utf-8")
    print(f"[OK] Synced {len(synced_lines)} lines to {WEB_ENV_LOCAL_PATH}")

if __name__ == "__main__":
    sync_env()
