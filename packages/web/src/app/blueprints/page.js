  const categories = ["All", "Workholding", "Tooling Fixtures", "Coolant Systems"];

  // Web Audio tone synthesizer to generate genuine acoustic frequencies
  const handlePlaySoundNote = (bp) => {
    if (typeof window === "undefined") return;

    try {
      const AudioCtx = window.AudioContext || window.webkitAudioContext;
      if (!AudioCtx) {
        console.warn("Web Audio API is not supported in this browser.");
        return;
      }

      // Close previous context if exists
      if (audioCtxRef.current) {
        try {
          audioCtxRef.current.close();
        } catch {}
      }

      const ctx = new AudioCtx();
      audioCtxRef.current = ctx;

      if (ctx.state === "suspended") {
        ctx.resume();
      }

      const freq = bp.soundNote?.frequency || 440;
      const type = bp.soundNote?.waveform || "sine";
      const duration = bp.soundNote?.duration || 1.6;
      const now = ctx.currentTime;

      // Primary tone oscillator
      const osc = ctx.createOscillator();
      const gain = ctx.createGain();

      osc.type = type;
      osc.frequency.setValueAtTime(freq, now);

      // Acoustic micro-modulation to simulate genuine machining chatter harmonics
      osc.frequency.exponentialRampToValueAtTime(freq * 0.99, now + 0.2);
      osc.frequency.setValueAtTime(freq, now + 0.4);

      // Natural acoustic envelope: crisp attack, subtle sustain, smooth exponential decay
      gain.gain.setValueAtTime(0.001, now);
      gain.gain.exponentialRampToValueAtTime(0.25, now + 0.04);
      gain.gain.exponentialRampToValueAtTime(0.12, now + 0.4);
      gain.gain.exponentialRampToValueAtTime(0.0001, now + duration);

      osc.connect(gain);
      gain.connect(ctx.destination);

      setPlayingToneId(bp.id);
      osc.start(now);
      osc.stop(now + duration);

      osc.onended = () => {
        setPlayingToneId(null);
        try {
          ctx.close();
        } catch {}
      };
    } catch (err) {
      console.warn("Audio tone synthesis error:", err);
      setPlayingToneId(null);
    }
  };

