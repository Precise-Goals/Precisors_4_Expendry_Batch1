const hre = require("hardhat");
const fs = require("fs");
const path = require("path");

async function main() {
  const [deployer] = await hre.ethers.getSigners();
  console.log("Deploying EXPEN token with account:", deployer.address);

  const balance = await hre.ethers.provider.getBalance(deployer.address);
  console.log("Account balance:", hre.ethers.formatEther(balance), "MST");

  const EXPENFactory = await hre.ethers.getContractFactory("EXPEN");
  console.log("Deploying contract...");
  const expen = await EXPENFactory.deploy(deployer.address);
  await expen.waitForDeployment();

  const expenAddress = await expen.getAddress();
  console.log("EXPEN deployed successfully to:", expenAddress);
  console.log(`Explorer link: https://testnet.mstscan.com/address/${expenAddress}`);

  // Extract ABI from Hardhat artifact
  const artifact = await hre.artifacts.readArtifact("EXPEN");

  // Export to packages/shared/src/contracts.js
  const sharedContractsPath = path.resolve(__dirname, "../../shared/src/contracts.js");
  const fileContent = `// Auto-generated by packages/contracts/scripts/deploy.js
export const EXPEN_ADDRESS = "${expenAddress}";
export const EXPEN_ABI = ${JSON.stringify(artifact.abi, null, 2)};
`;

  fs.writeFileSync(sharedContractsPath, fileContent, "utf-8");
  console.log("Exported address and ABI to:", sharedContractsPath);

  // Write deployments.json record
  const deploymentRecord = {
    network: hre.network.name,
    chainId: hre.network.config.chainId || (await hre.ethers.provider.getNetwork()).chainId.toString(),
    address: expenAddress,
    deployer: deployer.address,
    timestamp: new Date().toISOString(),
    explorerUrl: `https://testnet.mstscan.com/address/${expenAddress}`,
  };

  const rootDeploymentPath = path.resolve(__dirname, "../../../deployments.json");
  fs.writeFileSync(rootDeploymentPath, JSON.stringify(deploymentRecord, null, 2), "utf-8");
  console.log("Saved deployment record to:", rootDeploymentPath);
}

main().catch((error) => {
  console.error("Deployment failed:", error);
  process.exitCode = 1;
});
